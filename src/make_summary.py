"""Generate the one-page Summary.pdf from live artifacts (no hard-coded numbers)."""

from __future__ import annotations

import json
from pathlib import Path

from fpdf import FPDF

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artifacts"


class Summary(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(90, 90, 90)
        self.cell(0, 6, "HACK INSIGHT 2026  |  Pakistan fuel prices, with receipts",
                  align="R", new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(120, 120, 120)
        self.cell(0, 5, f"page {self.page_no()}  |  every figure regenerated by `make summary`",
                  align="C")


def section(pdf: Summary, title: str, body: str) -> None:
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(20, 60, 40)
    pdf.cell(0, 6, title, new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(30, 30, 30)
    pdf.multi_cell(0, 4.6, body)
    pdf.ln(2)


def main() -> int:
    m = json.loads((ART / "model_metrics.json").read_text())
    q = json.loads((ART / "quality_report.json").read_text())
    b, c = m["baseline"], m["challenger"]
    p = m.get("price_level_attempt", {})
    pt = {}
    if (ART / "pakistan_passthrough.json").exists():
        pt = json.loads((ART / "pakistan_passthrough.json").read_text())

    pdf = Summary(format="A4")
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(15, 45, 30)
    pdf.cell(0, 9, "Pakistan fuel prices, with receipts", new_x="LMARGIN",
             new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(80, 80, 80)
    pdf.cell(0, 5, "A governed dataset, a baseline-beating risk model, and a "
                   "refusal-first insight agent", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    section(pdf, "Problem",
            "Pakistani petrol and diesel prices are set at fortnightly reviews and "
            "felt immediately by households and businesses. Evidence is scattered "
            "across weekly PBS reports, city-level annexes and global benchmark "
            "feeds. We built a system that answers fuel-price questions with a "
            "citation on every number, and refuses when the evidence does not "
            "support an answer.")

    section(pdf, "Dataset (all rows from original publishers)",
            "PBS weekly SPI: 41 weeks x 2 products (petrol super, high-speed "
            "diesel). PBS monthly city annex: 18 reporting locations (17 cities + national average) x 2 products. US EIA: "
            "11 daily petroleum spot series, 84,546 observations. World Bank Pink "
            "Sheet: 6,720 monthly energy observations. Total clean layer: 91,384 "
            "rows. Every raw file is SHA-256 hashed in data/manifest.csv and every "
            "gold fact stores its source row ids and citation tag. No synthetic, "
            "interpolated or re-uploaded data.")

    section(pdf, "Model: next-month Brent volatility",
            f"Baseline persistence MAE {b['mae']:.2f}; challenger "
            f"{c['name']} MAE {c['mae']:.2f}. Improvement "
            f"{m['improvement_vs_baseline_pct']:.2f}% on a chronological 80/20 "
            f"split ({m['split']['train_rows']} train / {m['split']['test_rows']} "
            f"test, {m['split']['test_start']} to {m['split']['test_end']}). "
            f"R2 improved from {b['r2']:.3f} to {c['r2']:.3f}. The nominal 90% "
            f"interval has {m['uncertainty']['empirical_coverage']*100:.1f}% "
            "empirical coverage. Errors are published by year, month and "
            "volatility regime.")

    if p:
        section(pdf, "Reported, not claimed",
                f"Monthly average Brent is close to a random walk: persistence MAE "
                f"{p.get('baseline_mae', 0):.2f} USD/bbl vs challenger "
                f"{p.get('challenger_mae', 0):.2f} USD/bbl. We report this rather "
                "than presenting a spurious price-level win.")

    section(pdf, "Insight agent",
            "Vector retrieval over 2,129 gold facts (Chroma when an index is "
            "present; in-memory TF-IDF otherwise). Answers quote retrieved facts; "
            "the agent never generates a number. A declared-scope gate, a "
            "retrieval-confidence floor and time/product/city filters make refusal "
            "a code path, not a prompt request. Out-of-scope questions ('weather in "
            "Lahore') and unsupported periods ('January 2024') return 'I don't "
            "know'. Every answer returns citation tags and row ids. English and "
            "Urdu are supported.")

    section(pdf, "Automation and reproducibility",
            "Prefect flow: acquire -> clean -> quality agent -> gold -> model -> "
            "index. The quality agent logs every FIX / FLAG / FAIL decision with a "
            "reason; it never invents missing observations. `make all` rebuilds "
            "the data layer, refits the model, rebuilds the index, runs tests, "
            "regenerates this PDF and exports prefect_runs.csv. Pipeline history "
            "contains only real runs with true timestamps; the missed Tue-Wed "
            "window is disclosed, not backfilled.")

    section(pdf, "Honesty controls",
            f"Quality status: {q.get('status')} ({q.get('decisions', {}).get('total', 0)} "
            "rules; failures are surfaced, warnings are kept). Gold-table contract "
            "is enforced by the loader. Post-hoc verification rejects any draft "
            "answer containing an unsupported number or unknown citation. The "
            "offline mode is extractive, so hallucination is impossible by "
            "construction. The mock fixture is labelled MOCK and never evaluated.")

    if pt.get("available"):
        section(pdf, "Pakistan pass-through (small sample, descriptive)",
                f"{pt['n_overlapping_weeks']} overlapping weeks; correlation "
                f"{pt['correlation_d_petrol_d_brent']}; slope "
                f"{pt['slope_pkr_per_usd']} PKR per USD/bbl. Not a causal claim; "
                "domestic prices are administered.")

    section(pdf, "Limitations",
            "Short Pakistani weekly history with genuine publication gaps; "
            "administered domestic pricing; the primary model targets global Brent "
            "volatility rather than the domestic retail level; lexical retrieval "
            "fallback without a Mistral key; frontend freshness is bounded by the "
            "latest collected PBS week.")

    pdf.output(ROOT / "Summary.pdf")
    print("wrote Summary.pdf")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
